    private void connectionButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_connectionButtonActionPerformed
        String loginSaisi = IdInput.getText();
        String mdpSaisi = new String(passwordInput.getPassword());


        if (loginSaisi.isEmpty() || mdpSaisi.isEmpty()) {
            JOptionPane.showMessageDialog(this, 
                "Veuillez remplir tous les champs.", 
                "Attention", 
                JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        UserService userService = new UserService();
        try{
            
            // Si les crédentials sont correctes, on bascule vers la page Home
            User user = userService.getUser(loginSaisi, mdpSaisi);
            if(user != null){
                UserSession.getInstance().setUser(user); // On stock les informations de l'utilisateur dans une instance static
                
                HomePage home = new HomePage();
                home.setVisible(true);
                this.dispose();
                
            } else{
                JOptionPane.showMessageDialog(this, 
                    "Identifiants incorrects.", 
                    "Erreur d'authentification", 
                    JOptionPane.ERROR_MESSAGE
                );
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, 
                "Erreur de communication avec la base : " + e.getMessage(), 
                "Erreur SQL", 
                JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_connectionButtonActionPerformed

